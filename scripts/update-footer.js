#!/usr/bin/env node

/**
 * Keeps one header menu and one footer on every page.
 *
 * Usage: node scripts/update-footer.js [--check]
 *
 * The menu (site-nav markers) sits just before each page's <header>, or before
 * the hero on the homepage. Google builds sitelinks from a site's consistent
 * navigation, and before this no page had any: section pages linked only to
 * Home, About and Now through the footer.
 *
 * The footer had drifted into five variants: library.html had lost its LinkedIn
 * link, claude-skills.html had lost the flag, some pages used relative hrefs
 * that broke at /blog/<slug>/ depth, and the .with-border class was applied at
 * random. This script owns the markup and rewrites it everywhere.
 *
 * It runs LAST in CI, after update-blog.js and update-library.js, so pages those
 * scripts generate get normalised too and their templates need no changes.
 *
 * --check exits non-zero if any page is out of date, without writing.
 */

const fs = require('fs');
const path = require('path');
const { writeFileAtomic } = require('./lib');

const ROOT = path.join(__dirname, '..');

const START = '<!-- site-footer:start (generated by scripts/update-footer.js) -->';
const END = '<!-- site-footer:end -->';

// Full-screen self-contained pages. They deliberately have no site chrome, and
// bolting a footer onto them would overlay the game UI.
const SKIP_FILES = new Set([
  'cyber.html',
  'veridis-quo.html',
  'mazo/index.html'
]);

const SKIP_DIRS = new Set(['.git', 'node_modules', '.playwright-mcp', '.github', 'assets', 'videos']);

// Absolute hrefs only: the same block has to work at /, /blog/<slug>/ and
// /library/<slug>/. Relative paths were the reason nested pages drifted.
const NAV_LINKS = [
  { href: '/blog/', label: 'Blog', section: p => p.startsWith('/blog/') },
  { href: '/about', label: 'About', section: p => p === '/about' },
  { href: '/now', label: 'Now', section: p => p === '/now' },
  { href: '/library', label: 'Library', section: p => p === '/library' || p.startsWith('/library/') }
];

const NAV_START = '<!-- site-nav:start (generated by scripts/update-footer.js) -->';
const NAV_END = '<!-- site-nav:end -->';

const FOOTER_LINKS = [
  { href: '/', label: 'Home' },
  { href: '/blog/', label: 'Blog' },
  { href: '/about', label: 'About' },
  { href: '/now', label: 'Now' },
  { href: '/library', label: 'Library' },
  { href: 'https://x.com/peter_skaronis', label: 'Twitter' },
  { href: 'https://www.linkedin.com/in/peterskaronis/', label: 'LinkedIn' }
];

const COPYRIGHT = 'Made in Vancouver \u{1F1E8}\u{1F1E6}';

function renderFooter(indent = '    ') {
  const links = FOOTER_LINKS
    .map(l => `${indent}        <a href="${l.href}">${l.label}</a>`)
    .join('\n');

  return [
    `${indent}${START}`,
    `${indent}<footer class="with-border">`,
    `${indent}    <div class="footer-links">`,
    links,
    `${indent}    </div>`,
    `${indent}    <p class="copyright">${COPYRIGHT}</p>`,
    `${indent}</footer>`,
    `${indent}${END}`
  ].join('\n');
}

/** "blog/x/index.html" -> "/blog/x/";  "about.html" -> "/about" (same rule as update-seo.js). */
function urlPathFor(rel) {
  const p = rel.split(path.sep).join('/');
  if (p === 'index.html') return '/';
  if (p.endsWith('/index.html')) return '/' + p.slice(0, -'index.html'.length);
  return '/' + p.replace(/\.html$/, '');
}

function renderNav(indent, urlPath) {
  const links = NAV_LINKS
    .map(l => {
      const current = l.section(urlPath) ? ' aria-current="page"' : '';
      return `${indent}        <a href="${l.href}"${current}>${l.label}</a>`;
    })
    .join('\n');
  const home = urlPath === '/' ? ' aria-current="page"' : '';

  return [
    `${indent}${NAV_START}`,
    `${indent}<nav class="site-nav" aria-label="Main">`,
    `${indent}    <a href="/" class="site-nav-home"${home}>Peter Skaronis</a>`,
    `${indent}    <div class="site-nav-links">`,
    links,
    `${indent}    </div>`,
    `${indent}</nav>`,
    `${indent}${NAV_END}`
  ].join('\n');
}

const escapeRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const NAV_MARKED_RE = new RegExp(`([ \\t]*)${escapeRe(NAV_START)}[\\s\\S]*?${escapeRe(NAV_END)}`);
// Where a page's own chrome begins: its <header>, or the homepage hero.
const NAV_ANCHOR_RE = /^([ \t]*)(?=<header\b|<section class="hero")/m;

/** The page with its menu current, or null when there is nowhere to put one. */
function applyNav(html, rel) {
  const urlPath = urlPathFor(rel);
  if (NAV_MARKED_RE.test(html)) {
    const indent = html.match(NAV_MARKED_RE)[1] || '    ';
    return html.replace(NAV_MARKED_RE, renderNav(indent, urlPath));
  }
  const m = html.match(NAV_ANCHOR_RE);
  if (!m) return null;
  const indent = m[1] || '    ';
  return html.slice(0, m.index) + renderNav(indent, urlPath) + '\n' + html.slice(m.index);
}

function findHtmlFiles(dir, found = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      findHtmlFiles(path.join(dir, entry.name), found);
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      found.push(path.join(dir, entry.name));
    }
  }
  return found;
}

// Matches a whole <footer>...</footer> element plus the indentation on its line.
const FOOTER_RE = /([ \t]*)<footer\b[^>]*>[\s\S]*?<\/footer>/;
const MARKED_RE = new RegExp(
  `([ \\t]*)${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`
);

function countOccurrences(haystack, needleRe) {
  return (haystack.match(new RegExp(needleRe.source, 'g')) || []).length;
}

function processFile(filePath, { check }) {
  const rel = path.relative(ROOT, filePath);
  if (SKIP_FILES.has(rel)) return { rel, status: 'skipped' };

  const html = fs.readFileSync(filePath, 'utf8');

  // The menu first. A page with no <header> and no hero has nowhere obvious to
  // put one; never guess, report it.
  const withNav = applyNav(html, rel);
  if (withNav === null) return { rel, status: 'no-nav-anchor' };

  // Already migrated: rewrite whatever sits between the markers.
  if (MARKED_RE.test(withNav)) {
    const indent = withNav.match(MARKED_RE)[1] || '    ';
    const updated = withNav.replace(MARKED_RE, renderFooter(indent));
    if (updated === html) return { rel, status: 'current' };
    if (!check) writeFileAtomic(filePath, updated);
    return { rel, status: 'updated' };
  }

  const footerCount = countOccurrences(withNav, /<footer\b/);
  if (footerCount === 0) {
    // Never guess where a footer belongs. Report and move on.
    return { rel, status: 'no-footer' };
  }
  if (footerCount > 1) {
    return { rel, status: 'ambiguous' };
  }

  const indent = withNav.match(FOOTER_RE)[1] || '    ';
  const updated = withNav.replace(FOOTER_RE, renderFooter(indent));
  if (updated === html) return { rel, status: 'current' };
  if (!check) writeFileAtomic(filePath, updated);
  return { rel, status: 'migrated' };
}

function main() {
  const check = process.argv.includes('--check');
  const files = findHtmlFiles(ROOT).sort();

  const results = files.map(f => processFile(f, { check }));
  const by = status => results.filter(r => r.status === status);

  for (const r of results) {
    if (r.status === 'updated' || r.status === 'migrated') {
      console.log(`  ${r.status.padEnd(8)} ${r.rel}`);
    }
  }

  for (const r of by('no-footer')) {
    console.warn(`  WARNING  ${r.rel} has no <footer> and no markers -- add one or list it in SKIP_FILES`);
  }
  for (const r of by('no-nav-anchor')) {
    console.warn(`  WARNING  ${r.rel} has no <header> or hero to put the menu before -- add one or list it in SKIP_FILES`);
  }
  for (const r of by('ambiguous')) {
    console.warn(`  WARNING  ${r.rel} has multiple <footer> elements -- left untouched`);
  }

  const changed = by('updated').length + by('migrated').length;
  console.log(
    `\nFooter: ${by('current').length} current, ${changed} ${check ? 'out of date' : 'rewritten'}, ` +
    `${by('skipped').length} skipped, ${by('no-footer').length + by('ambiguous').length + by('no-nav-anchor').length} needing attention ` +
    `(${files.length} pages scanned)`
  );

  if (check && changed > 0) {
    console.error('\nFooters are out of date. Run: node scripts/update-footer.js');
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = { applyNav, renderNav, renderFooter, urlPathFor, NAV_LINKS, SKIP_FILES };
